// esbuild settings shared by the GitHub Action and the Azure DevOps task: one CommonJS file, Node 20 compatible, with
// the storeasy library taken from source. The bundles are committed because runners execute them as is.
import { build } from 'esbuild'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))

export const BUNDLES = {
  'upload-action': { outfile: 'dist/index.cjs', banner: 'storeasy upload action' },
  'azure-devops-task': { outfile: 'StoreasyUploadV1/dist/index.cjs', banner: 'storeasy Azure DevOps task StoreasyUpload@1' },
}

export function options(pkg) {
  const b = BUNDLES[pkg]
  return {
    entryPoints: [join(root, pkg, 'src', 'index.ts')],
    outfile: join(root, pkg, b.outfile),
    bundle: true,
    platform: 'node',
    target: 'node20',
    format: 'cjs',
    alias: { storeasy: join(root, 'storeasy-cli', 'src', 'index.ts') },
    legalComments: 'inline',
    banner: { js: `// ${b.banner}. SPDX-License-Identifier: AGPL-3.0-only. Generated by build.mjs; edit src/ instead.` },
    absWorkingDir: root,
    logLevel: 'info',
  }
}

export async function bundle(pkg) {
  await build(options(pkg))
}

/** True when the committed bundle equals a fresh build (line endings ignored). */
export async function isFresh(pkg) {
  const opts = options(pkg)
  const res = await build({ ...opts, write: false, logLevel: 'silent' })
  const fresh = res.outputFiles[0].text
  let committed = ''
  try {
    committed = readFileSync(opts.outfile, 'utf8')
  } catch {
    return false
  }
  const norm = (s) => s.replace(/\r\n/g, '\n')
  return norm(fresh) === norm(committed)
}
